def _merge(base: dict, over: dict) -> dict:
    out = dict(base)
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = _merge(out[k], v)
        else:
            out[k] = v
    return out


def load(path: Path | None = None) -> dict:
    """Load forge.json merged over the defaults. Missing file = defaults."""
    p = path or CONFIG_PATH
    cfg = dict(DEFAULTS)
    if p.exists():
        with open(p, "r", encoding="utf-8") as f:
            cfg = _merge(DEFAULTS, json.load(f))
    cfg["_root"] = str(ROOT)
    return cfg


def path_of(cfg: dict, key: str) -> Path:
    """Resolve a configured path; relative paths hang off the repo root."""
    raw = Path(cfg["paths"][key])
    p = raw if raw.is_absolute() else ROOT / raw
    p = p.resolve()
    if not cfg.get("allow_external_paths", False) and ROOT not in p.parents and p != ROOT:
        raise ValueError(f"path '{key}' = {p} is outside the repo; set allow_external_paths to permit it")
    return p


def model_dirs(cfg: dict, kind: str) -> list[Path]:
    """Existing folders for one kind of weight (checkpoints, loras, …), repo-relative or absolute."""
    out: list[Path] = []
    for raw in cfg.get("model_dirs", {}).get(kind, []):
        p = Path(raw)
        p = p if p.is_absolute() else ROOT / p
        if p.exists():
            out.append(p.resolve())
    return out


def extra_model_paths_yaml(cfg: dict) -> str:
    """ComfyUI's extra_model_paths.yaml: one entry per folder so every collection is visible to it."""
    lines = ["# generated by `python -m forge comfy-paths` from forge.json — edit forge.json, not this file"]
    n = 0
    for kind, raws in cfg.get("model_dirs", {}).items():
        for raw in raws:
            p = Path(raw)
            p = p if p.is_absolute() else ROOT / p
            if not p.exists():
                continue
            n += 1
            lines += [f"rpg_forge_{n}:", f"  base_path: {str(p.parent)}", f"  {kind}: {p.name}"]
    return "\n".join(lines) + "\n"


def ensure_dirs(cfg: dict) -> None:
    for key in ("jobs", "out", "models", "logs", "palettes"):
        path_of(cfg, key).mkdir(parents=True, exist_ok=True)
    jobs = path_of(cfg, "jobs")
    for sub in ("pending", "running", "done", "failed", "paused", "templates"):
        (jobs / sub).mkdir(exist_ok=True)


def game_config(cfg: dict, game: str | None) -> dict:
    """games/<game>/forge.game.json — a game's own palette, style prefix, sizes. Optional."""
    if not game:
        return {}
    p = path_of(cfg, "games") / game / "forge.game.json"
    if not p.exists():
        return {}
    with open(p, "r", encoding="utf-8") as f:
        return json.load(f)
